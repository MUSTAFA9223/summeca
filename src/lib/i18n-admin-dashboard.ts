const ADMIN_DASHBOARD_AR_TRANSLATIONS: Record<string, string> = {
  ...SHARED_AR,
  ...ADMIN_AR,
  ...USER_AR,
};

const NORMALIZED_ADMIN_DASHBOARD = new Map(
  Object.entries(ADMIN_DASHBOARD_AR_TRANSLATIONS).map(([english, arabic]) => [
    english.toLocaleLowerCase('en'),
    arabic,
  ]),
);

function preserveWhitespace(value: string, translated: string) {
  const leadingWhitespace = value.match(/^\s*/)?.[0] ?? '';
  const trailingWhitespace = value.match(/\s*$/)?.[0] ?? '';
  return `${leadingWhitespace}${translated}${trailingWhitespace}`;
}

function coreValue(value: string) {
  const leading = value.match(/^\s*/)?.[0].length ?? 0;
  const trailing = value.match(/\s*$/)?.[0].length ?? 0;
  return value.slice(leading, Math.max(leading, value.length - trailing));
}

function translateDynamic(core: string): string | null {
  let match = core.match(/^(\d[\d,]*) total orders$/i);
  if (match) return `${match[1]} طلبًا إجمالًا`;

  match = core.match(/^(\d[\d,]*) registered customers$/i);
  if (match) return `${match[1]} عميلًا مسجلًا`;

  match = core.match(/^Audit log of all payment webhook events — (\d[\d,]*) total$/i);
  if (match) return `سجل تدقيق لجميع أحداث Webhook الخاصة بالدفع — ${match[1]} إجمالًا`;

  match = core.match(/^(\d[\d,]*) total records?$/i);
  if (match) return `${match[1]} سجلًا إجمالًا`;

  match = core.match(/^Page (\d+) of (\d+)$/i);
  if (match) return `الصفحة ${match[1]} من ${match[2]}`;

  match = core.match(/^(\d[\d,]*) of (\d[\d,]*) used$/i);
  if (match) return `تم استخدام ${match[1]} من ${match[2]}`;

  match = core.match(/^(\d[\d,]*) downloads?$/i);
  if (match) return `${match[1]} تنزيل`;

  match = core.match(/^(\d[\d,]*) currencies$/i);
  if (match) return `${match[1]} عملات`;

  match = core.match(/^Renews (.+)$/i);
  if (match) return `يتجدد في ${match[1]}`;

  match = core.match(/^Connected to (\d+) admin chats?\. One alert is sent per new 30-minute visitor session\.$/i);
  if (match) return `متصل بـ ${match[1]} محادثة إدارة. يُرسل تنبيه واحد لكل جلسة زائر جديدة مدتها 30 دقيقة.`;

  match = core.match(/^Sent to (\d+) users?$/i);
  if (match) return `تم الإرسال إلى ${match[1]} مستخدم`;

  match = core.match(/^(\d+)m ago$/i);
  if (match) return `قبل ${match[1]} د`;

  match = core.match(/^(\d+)h ago$/i);
  if (match) return `قبل ${match[1]} س`;

  match = core.match(/^(\d+)d ago$/i);
  if (match) return `قبل ${match[1]} ي`;

  match = core.match(/^File uploaded securely; (\d+) existing purchases? reconciled\.$/i);
  if (match) return `تم رفع الملف بأمان ومطابقة ${match[1]} من المشتريات الحالية.`;

  match = core.match(/^Private file configured; (\d+) existing purchases? reconciled\.$/i);
  if (match) return `تمت تهيئة الملف الخاص ومطابقة ${match[1]} من المشتريات الحالية.`;

  match = core.match(/^Request failed \((\d+)\)\. Please try again\.$/i);
  if (match) return `فشل الطلب (${match[1]}). حاول مرة أخرى.`;

  match = core.match(/^Showing (\d+) of (\d+)$/i);
  if (match) return `عرض ${match[1]} من ${match[2]}`;

  return null;
}

export function translateAdminDashboardText(value: string): string {
  if (!value || !/[A-Za-z]/.test(value)) return value;

  const core = coreValue(value);
  const exact = ADMIN_DASHBOARD_AR_TRANSLATIONS[core];
  const normalized = NORMALIZED_ADMIN_DASHBOARD.get(core.toLocaleLowerCase('en'));
  const translated = exact ?? normalized ?? translateDynamic(core);

  return translated ? preserveWhitespace(value, translated) : value;
}
