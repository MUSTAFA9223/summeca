const NORMALIZED_HOMEPAGE = new Map(
  Object.entries(HOMEPAGE_AR_TRANSLATIONS).map(([english, arabic]) => [english.toLocaleLowerCase('en'), arabic]),
);

function preserveWhitespace(value: string, translated: string) {
  const leading = value.match(/^\s*/)?.[0] ?? '';
  const trailing = value.match(/\s*$/)?.[0] ?? '';
  return `${leading}${translated}${trailing}`;
}

export function translateHomepageText(value: string): string {
  if (!value || !/[A-Za-z]/.test(value)) return value;

  const leading = value.match(/^\s*/)?.[0] ?? '';
  const trailing = value.match(/\s*$/)?.[0] ?? '';
  const core = value.slice(leading.length, Math.max(leading.length, value.length - trailing.length));

  const exact = HOMEPAGE_AR_TRANSLATIONS[core]
    ?? NORMALIZED_HOMEPAGE.get(core.toLocaleLowerCase('en'));

  return exact ? preserveWhitespace(value, exact) : value;
}
